"""Generate docs/api.md from the docstrings, without importing SALOME."""
import ast
import inspect
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODULES = ("geometry", "pipelines", "idealized", "centerline", "profiles", "validation", "transforms", "cli")


def signature(node):
    return "({})".format(ast.unparse(node.args))


def render_function(node, level, owner=""):
    doc = inspect.cleandoc(ast.get_docstring(node) or "")
    return ["{} `{}{}{}`\n".format("#" * level, owner, node.name, signature(node)), "```text\n{}\n```\n".format(doc)]


def is_public(node):
    return not node.name.startswith("_") or node.name == "__init__"


def main():
    lines = ["# API reference\n", "Generated by `tools/generate_api_docs.py` from the docstrings.\n"]
    for module in MODULES:
        with open(os.path.join(ROOT, "aneupy", module + ".py"), "r", encoding="utf-8") as handle:
            tree = ast.parse(handle.read())
        lines.append("## `aneupy.{}`\n".format(module))
        lines.append("```text\n{}\n```\n".format(inspect.cleandoc(ast.get_docstring(tree) or "")))
        for node in tree.body:
            if isinstance(node, ast.FunctionDef) and is_public(node):
                lines.extend(render_function(node, 3))
            elif isinstance(node, ast.ClassDef) and is_public(node):
                lines.append("### class `{}`\n".format(node.name))
                lines.append("```text\n{}\n```\n".format(inspect.cleandoc(ast.get_docstring(node) or "")))
                for item in node.body:
                    if isinstance(item, ast.FunctionDef) and is_public(item) and item.name != "__init__":
                        lines.extend(render_function(item, 4, node.name + "."))
    with open(os.path.join(ROOT, "docs", "api.md"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))


if __name__ == "__main__":
    main()
